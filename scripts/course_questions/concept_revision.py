def apply(modules):
    result = []
    consumed = set()
    for doc, module in zip(['environment','bigdata','infrastructure','netflix'], modules, strict=True):
        groups = deepcopy(module.GROUPS)
        for group in groups:
            for index, variant in enumerate(group['variants'], 1):
                key = (doc, group['key'], index)
                if key in REVISIONS:
                    variant.update(REVISIONS[key])
                    consumed.add(key)
                    variant['reviewDecision'] = 'rewritten'
                else:
                    previous = variant['stem']
                    for before, after in WORDING.items():
                        variant['stem'] = variant['stem'].replace(before, after)
                    variant['reviewDecision'] = 'wording-only' if previous != variant['stem'] else 'retained'
                # A revision's explicit givens take priority over baseline code.
                if variant.get('exhibit') is None:
                    snippet = getattr(module, 'CODE_EXHIBITS', {}).get((group['key'], index-1))
                    if snippet:
                        variant['exhibit'] = code(snippet)
                variant['reviewKey'] = ':'.join(map(str, key))
        result.append(groups)
    assert consumed == set(REVISIONS)
    return result

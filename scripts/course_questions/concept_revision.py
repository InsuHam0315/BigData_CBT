REVISIONS = {}


def revise(doc, concept, round_no, stem, explanation, choices, *, exhibit=None):
    """First choice is correct before the generator balances answer positions."""
    assert len(choices) == 4 and all(len(c) == 2 for c in choices)
    key = (doc, concept, round_no)
    assert key not in REVISIONS
    REVISIONS[key] = dict(stem=stem, explanation=explanation, answer=0,
                          options=choices, exhibit=exhibit)


def table(columns, rows, code=None):
    value = dict(columns=columns, rows=rows)
    if code:
        value['code'] = code
    return value


def code(text):
    return table([], [], text)



def apply_source_alignment(lessons):
    assert set(CONTENT) == {l['id'] for l in lessons}
    for l in lessons:
        l['additionalSections'] = l['sections']
        l['sections'] = CONTENT[l['id']]
        l['corrections'] = CORRECTIONS.get(l['id'], [])
        refs = {}
        for block in l['sections'] + l['corrections']:
            ref = block['source']
            refs.setdefault(ref['sourceId'], set()).update(ref['pages'])
        l['sources'] = [dict(sourceId=k, pages=sorted(v)) for k,v in refs.items()]
        chars = sum(len(p) for s in l['sections']+l['additionalSections']+l['corrections'] for p in s['body'])
        l['minutes'] = max(15, round(chars / 140) + 6 * len(l['workedExamples']))
    assert sum(len(l['additionalSections']) for l in lessons) == 112

CORRECTIONS = {}


def pages(spec):
    result = []
    for part in spec.split(','):
        ends = [int(x) for x in part.split('-')]
        result.extend(range(ends[0], ends[-1] + 1))
    return sorted(set(result))


def add(id, source, text):
    sections = []
    for block in text.strip().split('## ')[1:]:
        header, body = block.strip().split('\n', 1)
        heading, spec = header.split(' | ')
        sections.append(dict(heading=heading, body=[p.strip() for p in body.strip().split('\n\n')],
                             source=dict(sourceId=source, pages=pages(spec))))
    CONTENT[id] = sections


